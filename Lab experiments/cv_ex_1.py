# Experiment: Basic Image Handling and Processing
# Read an image and convert it to Gray-scale

# Step 1: Import required libraries
import cv2
import matplotlib.pyplot as plt
from google.colab import files

# Step 2: Upload an image
uploaded = files.upload()

# Step 3: Get the uploaded image filename
filename = list(uploaded.keys())[0]

# Step 4: Read the image
image = cv2.imread(filename)

# Check whether image is successfully read
if image is None:
    print("Error: Image could not be read.")
else:
    print("Image successfully read!")
    print("Image shape:", image.shape)

    # Step 5: Convert BGR image to RGB for displaying
    image_rgb = cv2.cvtColor(image, cv2.COLOR_BGR2RGB)

    # Step 6: Convert the image to grayscale
    gray_image = cv2.cvtColor(image, cv2.COLOR_BGR2GRAY)

    # Step 7: Display original and grayscale images
    plt.figure(figsize=(12, 5))

    # Original image
    plt.subplot(1, 2, 1)
    plt.imshow(image_rgb)
    plt.title("Original Image")
    plt.axis("off")

    # Grayscale image
    plt.subplot(1, 2, 2)
    plt.imshow(gray_image, cmap="gray")
    plt.title("Gray-scale Image")
    plt.axis("off")

    plt.show()

    # Step 8: Save the grayscale image
    cv2.imwrite("grayscale_image.jpg", gray_image)

    print("Gray-scale image saved successfully as grayscale_image.jpg")